/**
 * Regenerate src/ui/east-asian-wide.ts from get-east-asian-width:
 * `bun scripts/generate-east-asian-wide.ts`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { eastAsianWidthType } from "get-east-asian-width";

const OUTPUT = new URL("../src/ui/east-asian-wide.ts", import.meta.url);
const PACKAGE = new URL(
  "../node_modules/get-east-asian-width/package.json",
  import.meta.url,
);
const RANGES_PER_LINE = 8;

const version: string = (
  JSON.parse(readFileSync(PACKAGE, "utf8")) as { version: string }
).version;

const ranges: [number, number][] = [];
for (let code = 0; code <= 0x10ffff; code += 1) {
  const type = eastAsianWidthType(code);
  if (type !== "wide" && type !== "fullwidth") continue;
  const last = ranges.at(-1);
  if (last && last[1] === code - 1) last[1] = code;
  else ranges.push([code, code]);
}

const packed = ranges.map(
  ([from, to]) => `${from.toString(16)}-${to.toString(16)}`,
);
const rows: string[] = [];
for (let i = 0; i < packed.length; i += RANGES_PER_LINE)
  rows.push(`  "${packed.slice(i, i + RANGES_PER_LINE).join(" ")}",`);

const source = `// Generated by \`bun scripts/generate-east-asian-wide.ts\` from
// get-east-asian-width ${version}. Do not edit by hand.
// Packed as hex "from-to" pairs because a literal array of tuples exceeds the FTA cap.

const PACKED: string = [
${rows.join("\n")}
].join(" ");

/** Inclusive code point ranges with East Asian Width Wide or Fullwidth. */
export const EAST_ASIAN_WIDE: readonly (readonly [number, number])[] = PACKED.split(
  " ",
).map((pair): readonly [number, number] => {
  const [from = "", to = ""] = pair.split("-");
  return [Number.parseInt(from, 16), Number.parseInt(to, 16)];
});

/** True when the terminal draws \`code\` in two columns. */
export function isEastAsianWide(code: number): boolean {
  let low = 0;
  let high = EAST_ASIAN_WIDE.length - 1;
  while (low <= high) {
    const middle = (low + high) >> 1;
    const range = EAST_ASIAN_WIDE[middle];
    if (range === undefined) return false;
    if (code < range[0]) high = middle - 1;
    else if (code > range[1]) low = middle + 1;
    else return true;
  }
  return false;
}
`;

writeFileSync(OUTPUT, source);
const format = Bun.spawnSync(
  ["bunx", "biome", "format", "--write", OUTPUT.pathname],
  { stdout: "inherit", stderr: "inherit" },
);
if (format.exitCode !== 0) process.exit(format.exitCode ?? 1);
