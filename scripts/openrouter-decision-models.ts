/**
 * Refresh src/modules/config/models/openrouter-decision-models.ts from
 * OpenRouter's public model list. New decision models are added with
 * `benchmarked: false`; models OpenRouter no longer lists are removed.
 * `benchmarked` and `incompatible` stay as people set them.
 *
 * In CI (.github/workflows/openrouter-models.yml) a change appends
 * `changed=true` to $GITHUB_OUTPUT and writes the PR body to
 * $RUNNER_TEMP/openrouter-models-pr.md.
 */
import { appendFileSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  OPENROUTER_DECISION_MODELS,
  type OpenRouterDecisionModels,
} from "../src/modules/config/models/openrouter-decision-models";

const MODELS_URL = "https://openrouter.ai/api/v1/models?output_modalities=all";
const MODULE_PATH = join(
  import.meta.dir,
  "..",
  "src/modules/config/models/openrouter-decision-models.ts",
);
const MODULE_HEADER =
  "// Generated by scripts/openrouter-decision-models.ts. Edit only `benchmarked` and `incompatible` by hand.";
const EXPLICIT_TYPE_IGNORE =
  "// biome-ignore lint/nursery/useExplicitType: `as const satisfies` keeps the literal ids; an annotation would widen them";
const LINE_WIDTH = 80;

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isDecisionModel(entry: Record<string, unknown>): boolean {
  const architecture = entry.architecture;
  const modalities = isRecord(architecture)
    ? architecture.output_modalities
    : [];
  return Array.isArray(modalities) && modalities.includes("decisions");
}

/** Sorted ids of the models whose output modalities include "decisions". */
export function decisionModelIds(response: unknown): string[] {
  if (!isRecord(response) || !Array.isArray(response.data)) {
    throw new Error("OpenRouter response has no data array");
  }
  const ids: string[] = [];
  for (const entry of response.data as unknown[]) {
    if (!isRecord(entry) || typeof entry.id !== "string") {
      throw new Error("OpenRouter response has an entry without a string id");
    }
    if (isDecisionModel(entry)) ids.push(entry.id);
  }
  if (ids.length === 0) {
    throw new Error("OpenRouter response lists no decision models");
  }
  return ids.sort();
}

export function updateDecisionModels(
  current: OpenRouterDecisionModels,
  ids: readonly string[],
): { next: OpenRouterDecisionModels; added: string[]; removed: string[] } {
  const wanted = new Set(ids);
  const models: Record<string, { readonly benchmarked: boolean }> = {};
  const added: string[] = [];
  for (const id of [...wanted].sort()) {
    if (id in current.incompatible) continue;
    const existing = current.models[id];
    if (existing === undefined) added.push(id);
    models[id] = existing ?? { benchmarked: false };
  }
  const removed = Object.keys(current.models)
    .filter((id) => !wanted.has(id))
    .sort();
  return {
    next: { models, incompatible: current.incompatible },
    added,
    removed,
  };
}

function renderSection(entries: Readonly<Record<string, string>>): string {
  return Object.keys(entries)
    .sort()
    .map((key) => {
      const flat = `    ${JSON.stringify(key)}: ${entries[key]},`;
      return flat.length <= LINE_WIDTH ? flat : flat.replace(": ", ":\n      ");
    })
    .join("\n");
}

/** Output that Biome's formatter leaves unchanged. */
export function renderDecisionModelsModule(
  list: OpenRouterDecisionModels,
): string {
  const models = Object.fromEntries(
    Object.entries(list.models).map(([id, { benchmarked }]) => [
      id,
      `{ benchmarked: ${benchmarked} }`,
    ]),
  );
  const reasons = Object.fromEntries(
    Object.entries(list.incompatible).map(([id, why]) => [
      id,
      JSON.stringify(why),
    ]),
  );
  return `${MODULE_HEADER}
export interface OpenRouterDecisionModels {
  readonly models: Readonly<Record<string, { readonly benchmarked: boolean }>>;
  readonly incompatible: Readonly<Record<string, string>>;
}

${EXPLICIT_TYPE_IGNORE}
export const OPENROUTER_DECISION_MODELS = {
  models: {
${renderSection(models)}
  },
  incompatible: {
${renderSection(reasons)}
  },
} as const satisfies OpenRouterDecisionModels;
`;
}

function bulletList(ids: readonly string[]): string {
  return ids.map((id) => `- \`${id}\``).join("\n") || "None.";
}

export function pullRequestBody(
  added: readonly string[],
  removed: readonly string[],
): string {
  return `Weekly refresh of the OpenRouter decision-model list.

## Added

${bulletList(added)}

New models start with \`benchmarked: false\`. If one is known not to work with our System One request, move it to \`incompatible\` with the reason.

## Removed

${bulletList(removed)}
`;
}

async function main(): Promise<void> {
  const response = await fetch(MODELS_URL);
  if (!response.ok) {
    throw new Error(`OpenRouter model list failed: HTTP ${response.status}`);
  }
  const ids = decisionModelIds(await response.json());
  const { next, added, removed } = updateDecisionModels(
    OPENROUTER_DECISION_MODELS,
    ids,
  );

  const before = readFileSync(MODULE_PATH, "utf8");
  writeFileSync(MODULE_PATH, renderDecisionModelsModule(next));
  const format = Bun.spawnSync(
    ["bunx", "biome", "format", "--write", MODULE_PATH],
    {
      stdout: "inherit",
      stderr: "inherit",
    },
  );
  if (format.exitCode !== 0) throw new Error("biome format failed");
  if (readFileSync(MODULE_PATH, "utf8") === before) {
    console.log("OpenRouter decision models unchanged");
    return;
  }

  const bodyPath = join(
    process.env.RUNNER_TEMP ?? tmpdir(),
    "openrouter-models-pr.md",
  );
  writeFileSync(bodyPath, pullRequestBody(added, removed));
  const output = process.env.GITHUB_OUTPUT;
  if (output !== undefined && output !== "")
    appendFileSync(output, "changed=true\n");
  console.log(
    `OpenRouter decision models changed: +${added.length} -${removed.length}`,
  );
}

if (import.meta.main) await main();
